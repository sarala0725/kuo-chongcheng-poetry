import fs from "node:fs";
import path from "node:path";
import opentype from "opentype.js";

const projectRoot = path.resolve(import.meta.dirname, "..");
const fontPath = path.join(projectRoot, "assets", "fonts", "HanWangShinSuMedium.ttf");
const outputPath = path.join(projectRoot, "hero-calligraphy-paths.js");
const fontBytes = fs.readFileSync(fontPath);
const fontBuffer = fontBytes.buffer.slice(
  fontBytes.byteOffset,
  fontBytes.byteOffset + fontBytes.byteLength,
);
const font = opentype.parse(fontBuffer);
const glyphs = {};

for (const character of Array.from("耕舍詩文集")) {
  const glyph = font.charToGlyph(character);
  const fontSize = 900;
  const probe = glyph.getPath(0, 0, fontSize);
  const box = probe.getBoundingBox();
  const x = (1024 - (box.x2 - box.x1)) / 2 - box.x1;
  const y = (1024 - (box.y2 - box.y1)) / 2 - box.y1;
  const outline = glyph.getPath(x, y, fontSize);
  const strokeFile = `${character.codePointAt(0).toString(16).padStart(4, "0")}.json`;
  const strokeData = JSON.parse(
    fs.readFileSync(path.join(projectRoot, "assets", "hanzi-strokes", strokeFile), "utf8"),
  );
  glyphs[character] = {
    viewBox: "0 0 1024 1024",
    path: outline.toPathData(2),
    medians: strokeData.medians,
  };
}

const contents =
  "/* Generated by tools/build-hero-calligraphy.mjs. */\n" +
  `window.GS_HERO_CALLIGRAPHY = ${JSON.stringify(glyphs)};\n`;

fs.writeFileSync(outputPath, contents);
console.log(`Generated ${outputPath}`);
